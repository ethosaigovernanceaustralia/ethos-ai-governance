'use strict';

// For HTML text and quoted attributes, never JavaScript or URL contexts.
function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, char => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
  })[char]);
}

module.exports = { escapeHtml };
